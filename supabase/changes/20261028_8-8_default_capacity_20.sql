-- 8-8) 기본 정원을 모든 수업 20명으로 통일 (토요일도 20명)
--   사람이 많아지면 코치가 예약 화면에서 날짜별로 정원을 30명으로 늘립니다. (이미 늘려 둔 날짜는 그대로 유지)
--   이 SQL은 시간표의 "평소 정원"만 바꿉니다. 이미 예약한 사람이 정원보다 많아지는 일은 없고,
--   (정원이 줄어도 기존 예약은 취소되지 않습니다. 새 예약은 빈자리가 생길 때까지 대기)
-- 실행: Supabase 대시보드 → SQL Editor에 붙여넣고 Run
-- =========================================================
update public.class_slots set capacity = 20 where capacity <> 20;

-- 확인: 모두 20이면 한 줄만 나옵니다.
select capacity, count(*) as 칸수 from public.class_slots group by capacity;
